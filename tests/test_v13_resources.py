class EvaluationPortTests(unittest.TestCase):
    def test_catalog_aliases_share_guidance_and_all_entrypoints_are_mapped(self):
        catalog = yaml.safe_load(read("testing/catalog.yaml"))
        entries = json.loads((ROOT / ".game-studio/entrypoints.json").read_text(encoding="utf-8"))
        skills = {row["name"]: row for row in catalog["skills"]}
        roles = {row["name"]: row for row in catalog["roles"]}
        self.assertEqual(len(skills), len(catalog["skills"]))
        self.assertEqual(set(skills), set(entries["skills"]))
        self.assertEqual(set(roles), set(entries["roles"]))
        aliases = {"help": "next-step", "settings": "project-settings", "changelog": "write-changelog"}
        for old, new in aliases.items():
            self.assertEqual(skills["gs-" + old]["alias_of"], "gs-" + new)
            self.assertEqual(skills["gs-" + old]["spec"], skills["gs-" + new]["spec"])
            self.assertFalse((RES / "testing/skills" / (old + ".md")).exists())
        for row in [*skills.values(), *roles.values()]:
            path = RES / "testing" / row["spec"]
            self.assertTrue(path.is_file(), path)
            ids = re.findall(r"(?m)^### Case ([\w.-]+):", path.read_text(encoding="utf-8"))
            self.assertEqual(len(ids), len(set(ids)), path)

    def test_new_cases_preserve_independent_branches(self):
        expected = {"brainstorm": [7, 8], "next-step": [9, 10], "setup-engine": [9, 10, 11],
                    "start": [9, 10, 11, 12, 13], "prototype": [8, 9, 10, 11, 12],
                    "cut": list(range(1, 9))}
        for skill, ids in expected.items():
            for number in ids:
                with self.subTest(skill=skill, case=number):
                    text = case(skill, number)
                    self.assertIn("**Fixture:**", text)
                    self.assertIn("**Input:**", text)
                    self.assertIn("**Domain checks:**", text)
        self.assertIn("workspaces", case("setup-engine", 9).lower())
        self.assertIn("12-file", case("next-step", 9))
        self.assertIn("third run", case("prototype", 9))
        self.assertIn("staged-failure intent", case("prototype", 11))
        self.assertIn("Existing brief", case("prototype", 12))
        self.assertIn("Restore only", case("cut", 8))
        self.assertIn("polish only", case("cut", 7))

    def test_reviewed_native_failure_and_parent_branches_survive(self):
        self.assertIn("resume", case("dev-story", 9))
        self.assertIn("INCOMPLETE", case("dev-story", 9))
        smoke = read("testing/skills/smoke-check.md")
        for text in ["confirmed NOT RUN", "zero executed tests", "NOT ASSESSED",
                     "failures still outrank"]:
            self.assertIn(text, smoke)
        team = read("testing/skills/team-combat.md")
        self.assertIn("Parent execution path", team)
        self.assertIn("capacity below the full roster", team)
        self.assertIn("partial report", team)
        self.assertIn("at most one", case("code-review", 1))
        self.assertIn("lack of independence", case("code-review", 1))
        self.assertIn("sections 5–8 stay in conversation", case("art-bible", 1))
        self.assertIn("no specialist agent is launched", case("design-system", 1))
        self.assertIn("no helper is launched", case("architecture-review", 5))

    def test_feature_marks_and_goal_acceptance_have_both_branches(self):
        stories = case("create-stories", 6)
        self.assertIn("built item 1", stories)
        self.assertIn("items 2 and 3", stories)
        self.assertIn("without renumbering", stories)
        self.assertIn("Legacy MVP", stories)
        self.assertIn("declined save", case("start", 6))
        self.assertIn("Don't save", case("start", 12))
        self.assertIn("do not persist", case("cut", 3))
        self.assertIn("not Codex results", read("testing/README.md"))


