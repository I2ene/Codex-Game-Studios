"""Content regressions for the v1.3 native resource port (no model/game execution)."""
from pathlib import Path
import json
import re
import unittest

import yaml

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / ".game-studio" / "resources"


def read(relative):
    return (RES / relative).read_text(encoding="utf-8")


def case(skill, number):
    text = read(f"testing/skills/{skill}.md")
    match = re.search(rf"(?m)^### Case {number}:", text)
    if not match:
        raise AssertionError(f"{skill}: missing case {number}")
    return re.split(r"(?m)^### Case |^## Applicable domain checks",
                    text[match.end():], maxsplit=1)[0]


class GenreResourceTests(unittest.TestCase):
    def test_index_and_every_sheet_keep_the_full_design_shape(self):
        data = yaml.safe_load(read("genres/chipsets.yaml"))["chipsets"]
        sheets = {p.stem: p for p in (RES / "genres/chipsets").glob("*.md")}
        self.assertEqual(set(data), set(sheets))
        self.assertEqual(len(data), 69)
        required = ["Card defaults", "Feel", "Feel variants", "Choices that shape the pitch",
                    "Later, never in a one-shot", "In a mashup"]
        for name, path in sheets.items():
            with self.subTest(genre=name):
                text = path.read_text(encoding="utf-8")
                self.assertEqual(re.findall(r"(?m)^## (.+)$", text), required)
                self.assertTrue(data[name]["is"])
                self.assertTrue(data[name]["matches"])
                defaults = text.split("## Card defaults", 1)[1].split("## Feel variants", 1)[0]
                for item in re.split(r"(?m)^- ", defaults)[1:]:
                    self.assertIn("Why:", item)
                    self.assertRegex(item, r"Break\s+(?:it\s+)?when:")
                later = text.split("## Later, never in a one-shot", 1)[1].split("## In a mashup", 1)[0]
                self.assertIn("→", later)

    def test_source_keys_resolve_and_research_gaps_stay_visible(self):
        sources = read("genres/sources.md")
        keys = set(re.findall(r"\*\*\[([a-z0-9-]+)\]\*\*", sources))
        self.assertTrue(keys)
        for path in (RES / "genres/chipsets").glob("*.md"):
            for key in re.findall(r"\[([a-z][a-z0-9-]*-\d+)\]", path.read_text(encoding="utf-8")):
                with self.subTest(sheet=path.name, key=key):
                    self.assertIn(key, keys)
        scope = read("genres/README.md")
        self.assertIn("not measured balance targets", scope)
        self.assertIn("do not record Codex", scope)
        self.assertIn("hypothesis", read("genres/chipsets.yaml"))

    def test_exceptions_and_network_limits_are_not_flattened_to_defaults(self):
        racing = read("genres/chipsets/racing.md")
        self.assertIn("time trial", racing)
        self.assertIn("no rivals and no catch-up", racing)
        self.assertIn("needs a server: not built yet", racing)
        physics = read("genres/chipsets/physics-puzzle.md")
        self.assertIn("fixed step", physics)
        self.assertIn("chaos is the fun", physics)
        self.assertIn("recorded clear", physics)
        self.assertNotIn("no solver can search physics", physics)
        online = read("genres/online-and-devices.md")
        self.assertIn("stand-in", online)
        self.assertIn("no check plays them", online)


